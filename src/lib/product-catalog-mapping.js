// Función helper para obtener imágenes secundarias
export function getSecondaryImage(productName) {
  // Buscar coincidencia exacta primero
  if (CATALOG_IMAGE_MAPPING[productName]) {
    return CATALOG_IMAGE_MAPPING[productName].secondaryImage;
  }
  
  // Buscar coincidencia parcial (case insensitive)
  const normalizedName = productName.toLowerCase().trim();
  for (const [key, value] of Object.entries(CATALOG_IMAGE_MAPPING)) {
    if (key.toLowerCase().includes(normalizedName) || normalizedName.includes(key.toLowerCase())) {
      return value.secondaryImage;
    }
  }
  
  return null;
}

// Función para obtener todas las imágenes de un producto
export function getProductImages(productName, primaryImage) {
  const secondaryImage = getSecondaryImage(productName);
  const images = [primaryImage];
  if (secondaryImage) {
    images.push(secondaryImage);
  }
  return images;
}
